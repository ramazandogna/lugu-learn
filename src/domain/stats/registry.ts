export type StatGroup = 'exam' | 'lesson' | 'mastery' | 'time' | 'habit' | 'task' | 'speaking' | 'period'
export type Direction = 'higher_better' | 'lower_better' | 'neutral'
export type StatUnit =
  | 'net' | 'percent' | 'ratio' | 'count' | 'seconds' | 'minutes' | 'ms' | 'days'
  | 'points' | 'flag' | 'rank' | 'per_week' | 'per_hour' | 'slope' | 'z' | 'metric'
export type StatParamNeed = 'subjectId' | 'lessonId' | 'nth' | 'n' | 'statId' | 'k'

export interface StatMeta {
  /** snake_case, sabit, spec'teki id ile birebir */
  id: string
  /** Türkçe ad (spec "Ad") */
  name: string
  group: StatGroup
  direction: Direction
  unit: StatUnit
  /** spec "Pencere" tipleri; ilki varsayılan */
  windows: readonly WindowKind[]
  /** zorunlu param; eksikse runStat not_applicable döner */
  needs: readonly StatParamNeed[]
  /** spec kenar durumundaki en az nokta */
  minN: number
  /** yalnız yeni tablolara bağlı statlar */
  schema?: '0011'
  /** spec "Yorum ipucu" (admin metni) */
  hint: string
  fn: (input: StatsInput, params: StatParams) => StatResult
}

