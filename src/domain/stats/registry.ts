export type StatId = keyof typeof STAT_REGISTRY

export function listStats(group?: StatGroup): StatMeta[] {
  const all: StatMeta[] = Object.values(STAT_REGISTRY)
  return group === undefined ? all : all.filter(m => m.group === group)
}

/** Zorunlu param kontrolü, zaman penceresi, sonra stat fonksiyonu. */
export function runStat(id: StatId, input: StatsInput, params: StatParams): StatResult {
  const meta: StatMeta = STAT_REGISTRY[id]
  for (const need of meta.needs) {
    if (params[need] == null) return { value: null, n: 0, reason: 'not_applicable' }
  }
  return meta.fn(scopeInput(input, resolveRange(params)), params)
}
